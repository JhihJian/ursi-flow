  test('产物 Markdown 预览、源文件与实际下载内容一致', async ({ page }, testInfo) => {
    await page.goto('/artifacts')
    await page.getByRole('button', { name: /代码审查报告\.md/ }).click()
    await expect(page.getByRole('heading', { name: '支付重试审查报告', exact: true })).toBeVisible()
    await page.getByRole('tab', { name: '源文件' }).click()
    const source = await page.locator('pre').innerText()
    expect(source).toContain('# 支付重试审查报告')
    const downloading = page.waitForEvent('download')
    await page.getByRole('button', { name: '下载文件' }).click()
    const download = await downloading
    expect(download.suggestedFilename()).toBe('代码审查报告.md')
    const file = testInfo.outputPath(download.suggestedFilename())
    await download.saveAs(file)
    expect(await readFile(file, 'utf8')).toBe(source)
    await page.getByRole('tab', { name: '内容预览' }).click()
    await expect(page.getByRole('heading', { name: '审查记录', exact: true })).toBeVisible()
    await page.getByRole('link', { name: '支付重试逻辑 · 审查完成', exact: true }).click()
    await expect(page).toHaveURL(/\/runs\/run-2$/)
  })

